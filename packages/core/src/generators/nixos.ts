import { GeneratedRecipe, UserCriteria } from '../types.js';
import { getDockerApp } from './docker-apps.js';

const NIX_PACKAGE_MAP: Readonly<Record<string, string>> = {
  firefox: 'pkgs.firefox',
  chromium: 'pkgs.chromium',
  brave: 'pkgs.brave',
  vscode: 'pkgs.vscode',
  'git-dev': 'pkgs.git',
  neovim: 'pkgs.neovim',
  nodejs: 'pkgs.nodejs',
  python: 'pkgs.python3',
  vlc: 'pkgs.vlc',
  obs: 'pkgs.obs-studio',
  gimp: 'pkgs.gimp',
  blender: 'pkgs.blender',
  spotify: 'pkgs.spotify',
  libreoffice: 'pkgs.libreoffice-fresh',
  discord: 'pkgs.discord',
  obsidian: 'pkgs.obsidian',
  telegram: 'pkgs.telegram-desktop',
  btop: 'pkgs.btop',
  fastfetch: 'pkgs.fastfetch'
};

function resolveNixArch(arch?: string): string {
  switch (arch) {
    case 'arm64':
      return 'aarch64-linux';
    case 'riscv64':
      return 'riscv64-linux';
    case 'x86_64':
    default:
      return 'x86_64-linux';
  }
}

export function generateNixosRecipe(criteria: UserCriteria): GeneratedRecipe {
  const nixSystem = resolveNixArch(criteria.architecture);
  const hostname = 'tailor-nixos';
  const username = 'tailor';

  const selectedPackages = (criteria.desktopApps || [])
    .map((id) => NIX_PACKAGE_MAP[id])
    .filter(Boolean);

  if (criteria.enableDistrobox) {
    selectedPackages.push('pkgs.distrobox');
  }

  // Desktop environment configuration
  let desktopConfig = '';
  if (criteria.prefersGui !== false) {
    switch (criteria.desktopEnv) {
      case 'kde':
        desktopConfig = `  # KDE Plasma 6 Desktop Environment
  services.desktopManager.plasma6.enable = true;
  services.displayManager.sddm.enable = true;`;
        break;
      case 'xfce':
        desktopConfig = `  # Lightweight XFCE Desktop
  services.xserver.enable = true;
  services.xserver.desktopManager.xfce.enable = true;
  services.displayManager.lightdm.enable = true;`;
        break;
      case 'cage':
        desktopConfig = `  # Cage Wayland Kiosk / Single-App Compositor
  programs.cage.enable = true;`;
        break;
      case 'gnome':
      default:
        desktopConfig = `  # GNOME Desktop Environment
  services.xserver.enable = true;
  services.xserver.displayManager.gdm.enable = true;
  services.xserver.desktopManager.gnome.enable = true;`;
        break;
    }
  }

  // Audio configuration
  let audioConfig = '';
  if (criteria.realtimeAudio) {
    audioConfig = `
  # Pro-Audio / Low-Latency Sound Stack (PipeWire + RTKit)
  security.rtkit.enable = true;
  services.pipewire = {
    enable = true;
    alsa.enable = true;
    alsa.support32Bit = true;
    pulse.enable = true;
    jack.enable = true;
  };`;
  }

  // Docker container app configuration
  const dockerAppDef = getDockerApp(criteria.dockerApp);
  let containerConfig = '';
  if (dockerAppDef) {
    containerConfig = `
  # Container Appliance (${dockerAppDef.name})
  virtualisation.docker.enable = true;
  users.users.${username}.extraGroups = [ "docker" ];`;
  } else if (criteria.enableDistrobox) {
    containerConfig = `
  # Container Runtime for Distrobox / Podman
  virtualisation.podman = {
    enable = true;
    dockerCompat = true;
  };`;
  }

  const flakeContent = `{
  description = "Tailored NixOS System Configuration generated by DistroTailor";

  inputs = {
    nixpkgs.url = "github:nixos/nixpkgs/nixos-24.11";
  };

  outputs = { self, nixpkgs, ... }@inputs: {
    nixosConfigurations.${hostname} = nixpkgs.lib.nixosSystem {
      system = "${nixSystem}";
      modules = [
        ./configuration.nix
      ];
    };
  };
}
`;

  const packagesFormatted = selectedPackages.length > 0
    ? selectedPackages.map((p) => `    ${p}`).join('\n')
    : '    # Core utilities\n    pkgs.curl\n    pkgs.git\n    pkgs.htop';

  const configurationContent = `# ==============================================================================
# DistroTailor: Pure Declarative NixOS Configuration
# Host: ${hostname} | Arch: ${nixSystem}
# ==============================================================================
{ config, pkgs, ... }:

{
  system.stateVersion = "24.11";

  # Bootloader (UEFI / systemd-boot)
  boot.loader.systemd-boot.enable = true;
  boot.loader.efi.canTouchEfiVariables = true;

  # Networking
  networking.hostName = "${hostname}";
  networking.networkmanager.enable = true;

  # Localization & Time
  time.timeZone = "UTC";
  i18n.defaultLocale = "en_US.UTF-8";

${desktopConfig ? desktopConfig + '\n' : ''}${audioConfig ? audioConfig + '\n' : ''}${containerConfig ? containerConfig + '\n' : ''}
  # User Account (Non-root with sudo privileges)
  users.users.${username} = {
    isNormalUser = true;
    description = "Tailored User";
    extraGroups = [ "wheel" "networkmanager" ];
    initialPassword = "changeme"; # Required first-login credential; update via 'passwd'
  };

  # System-wide Packages
  environment.systemPackages = with pkgs; [
${packagesFormatted}
  ];

  # Nix Flakes & Command Line Tools
  nix.settings.experimental-features = [ "nix-command" "flakes" ];

  # Security & Firewall
  networking.firewall.enable = true;
}
`;

  const makefileContent = `# ==============================================================================
# DistroTailor: NixOS Flake Automation Makefile
# Target: ${hostname} (${nixSystem})
# ==============================================================================

HOSTNAME ?= ${hostname}

.PHONY: all check test-vm switch iso clean

all: check test-vm

# Validate flake syntax and configuration
check:
	@echo "[+] Checking Nix flake syntax..."
	nix flake check

# Build and run an isolated QEMU test-drive virtual machine (Zero Risk)
test-vm:
	@echo "[+] Building disposable QEMU test VM..."
	nixos-rebuild build-vm --flake .#$(HOSTNAME)
	@echo "[+] Launching VM (Press Ctrl+A then X to exit QEMU)..."
	./result/bin/run-$(HOSTNAME)-vm

# Deploy and switch this configuration on the running target machine
switch:
	@echo "[+] Switching running system to tailored configuration..."
	sudo nixos-rebuild switch --flake .#$(HOSTNAME)

# Build a standalone bootable live ISO image
iso:
	@echo "[+] Building bootable installer ISO image..."
	nix build .#nixosConfigurations.$(HOSTNAME).config.system.build.isoImage

clean:
	@echo "[+] Cleaning build outputs..."
	rm -f result
`;

  const readmeContent = `# ❄️ Tailored NixOS Flake

Generated by **DistroTailor** for target architecture \`${nixSystem}\`.

## 📦 What Is Inside
- **\`flake.nix\`**: Lockable, reproducible system inputs pinned to NixOS 24.11.
- **\`configuration.nix\`**: Declarative specification of desktop environment, user accounts, and curated application suites.
- **\`Makefile\`**: Instant one-line commands for verification, testing, and deployment.

---

## 🚀 Quickstart: 3-Tier Verification

### Tier 1: Zero-Risk VM Sandbox
Test-drive this exact configuration in an isolated virtual machine without touching your host drives:
\`\`\`bash
make test-vm
\`\`\`
*Credentials in VM: username \`${username}\`, password \`changeme\`.*

### Tier 2: Deploy to Running NixOS Machine
To switch a running NixOS installation to this new tailored flake:
\`\`\`bash
make switch
\`\`\`
*To rollback if anything is amiss:*
\`\`\`bash
sudo nixos-rebuild --rollback
\`\`\`

### Tier 3: Build a Bootable Live ISO
To produce a bootable ISO disk for flashing to a USB thumbdrive:
\`\`\`bash
make iso
\`\`\`
`;

  return {
    id: 'nixos-flake',
    title: 'NixOS Declarative Flake & VM Harness',
    summary: 'Fully declarative NixOS system flake with instant VM sandbox and atomic rollback support',
    targetFormat: 'iso',
    hostDependencies: ['nix', 'qemu'],
    estimatedBuildTimeMinutes: 5,
    quickstartCommands: [
      'make test-vm       # Instant test-drive in isolated QEMU virtual machine',
      'sudo make switch   # Deploy to physical machine or target host'
    ],
    files: [
      {
        filename: 'flake.nix',
        description: 'Reproducible NixOS system flake declaring inputs, outputs, and target system',
        content: flakeContent
      },
      {
        filename: 'configuration.nix',
        description: 'Declarative system configuration (users, desktop, packages, services)',
        content: configurationContent
      },
      {
        filename: 'Makefile',
        description: 'Automated test, VM preview, and deployment targets',
        content: makefileContent
      },
      {
        filename: 'README.md',
        description: 'Step-by-step instructions for testing and deployment',
        content: readmeContent
      }
    ]
  };
}
