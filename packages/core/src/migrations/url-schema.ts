/**
 * URL Schema Versioning and Migration Engine for DistroTailor.
 * 
 * CORE SCHEMA INVARIANT:
 * 1. Only bump CURRENT_SCHEMA_VERSION upon actual deployment/release.
 * 2. Only bump CURRENT_SCHEMA_VERSION when a BREAKING change to parameter names,
 *    removed criteria keys, or structural question criteria changes occurs.
 * 3. Additive non-breaking enhancements (new distros, optional parameters,
 *    new non-destructive tips or questions) MUST remain on the current schema version.
 */

import { UserCriteria } from '../types.js';
import { sanitizeCriteria, UntrustedCriteria } from '../taxonomy/criteria-schema.js';

export const CURRENT_SCHEMA_VERSION = 1;
export const MINIMUM_SUPPORTED_SCHEMA_VERSION = 1;

export type SchemaCompatibilityStatus =
  | 'valid'
  | 'migrated'
  | 'unsupported-too-old'
  | 'unsupported-too-new';

export interface MigrationResult {
  version: number;
  inputVersion: number;
  status: SchemaCompatibilityStatus;
  supported: boolean;
  migrated: boolean;
  fallbackNotice?: string;
  warnings: string[];
  params: Record<string, string>;
}

/**
 * Migration functions: fromVersion -> transform parameters to fromVersion + 1.
 */
export type SchemaMigrator = (
  params: Record<string, string>,
  warnings: string[]
) => Record<string, string>;

export const SCHEMA_MIGRATIONS: Record<number, SchemaMigrator> = {
  // Example for future migrations:
  // 1: (params, warnings) => {
  //   if (params.useCase === 'old-name') {
  //     params.useCase = 'new-name';
  //     warnings.push("Migrated useCase 'old-name' to 'new-name'");
  //   }
  //   return params;
  // }
};

/**
 * Criteria value aliases for backward compatibility with renamed or simplified taxonomy options.
 */
export const CRITERIA_VALUE_ALIASES: Record<string, Record<string, string>> = {
  useCase: {
    'home-automation': 'smart-home',
    'single-app': 'appliance-product',
    'kodi-media': 'media-center',
    'retro-gaming': 'gaming',
    'ai-ml': 'ai-gpu-compute',
    'crypto-mining': 'ai-gpu-compute'
  },
  platform: {
    rpi: 'embedded-sbc',
    raspberrypi: 'embedded-sbc',
    pc: 'bare-metal'
  },
  architecture: {
    x86: 'x86_64',
    amd64: 'x86_64',
    aarch64: 'arm64'
  }
};

/**
 * Migrates URL parameters from an arbitrary schema version to CURRENT_SCHEMA_VERSION.
 * Handles unversioned legacy links, renamed keys, aliases, and unsupported versions.
 */
export function migrateUrlParameters(rawParams: Record<string, string>): MigrationResult {
  const warnings: string[] = [];
  const versionParam = rawParams.v || rawParams.version;
  const parsedVersion = versionParam ? parseInt(versionParam, 10) : 1;
  const inputVersion = isNaN(parsedVersion) ? 1 : parsedVersion;

  let currentParams: Record<string, string> = { ...rawParams };
  let currentVersion = inputVersion;
  let migrated = false;

  // Intercept unsupported older schemas
  if (inputVersion < MINIMUM_SUPPORTED_SCHEMA_VERSION) {
    return {
      version: CURRENT_SCHEMA_VERSION,
      inputVersion,
      status: 'unsupported-too-old',
      supported: false,
      migrated: false,
      fallbackNotice: `This shared configuration was created with an older version (schema v${inputVersion}) that is no longer supported.`,
      warnings: [`Unsupported schema version v${inputVersion} (minimum supported is v${MINIMUM_SUPPORTED_SCHEMA_VERSION})`],
      params: currentParams
    };
  }

  // Intercept future schemas (e.g. link generated by newer dev/beta version)
  if (inputVersion > CURRENT_SCHEMA_VERSION) {
    return {
      version: CURRENT_SCHEMA_VERSION,
      inputVersion,
      status: 'unsupported-too-new',
      supported: false,
      migrated: false,
      fallbackNotice: `This shared configuration was created with a newer version (schema v${inputVersion}). Please refresh or check the latest release.`,
      warnings: [`Future schema version v${inputVersion} detected (current is v${CURRENT_SCHEMA_VERSION})`],
      params: currentParams
    };
  }

  // Run sequential step-by-step schema migrations if input is from older supported version
  while (currentVersion < CURRENT_SCHEMA_VERSION) {
    const migrator = SCHEMA_MIGRATIONS[currentVersion];
    if (migrator) {
      currentParams = migrator(currentParams, warnings);
      migrated = true;
    }
    currentVersion++;
  }

  // Apply value alias mappings
  for (const [key, aliases] of Object.entries(CRITERIA_VALUE_ALIASES)) {
    const val = currentParams[key];
    if (val && aliases[val]) {
      const canonical = aliases[val];
      warnings.push(`Aliased '${key}=${val}' to canonical '${canonical}'`);
      currentParams[key] = canonical;
      migrated = true;
    }
  }

  // Set the current schema version
  if (currentParams.v !== String(CURRENT_SCHEMA_VERSION)) {
    currentParams.v = String(CURRENT_SCHEMA_VERSION);
    if (!versionParam) {
      migrated = true; // Added missing version parameter
    }
  }

  return {
    version: CURRENT_SCHEMA_VERSION,
    inputVersion,
    status: migrated ? 'migrated' : 'valid',
    supported: true,
    migrated,
    warnings,
    params: currentParams
  };
}

/**
 * Universally parses normalized URL/query parameter key-values into strongly typed UserCriteria,
 * ensuring complete parity across Web, CLI, and API consumers.
 */
export function deserializeCriteriaFromParams(params: Record<string, string>): UserCriteria {
  const flag = (value: string | undefined): boolean | undefined =>
    value === undefined ? undefined : value === 'true' || value === '1';
  const list = (value: string | undefined): string[] | undefined =>
    value ? value.split(',').filter(Boolean) : undefined;

  const raw: UntrustedCriteria = {
    useCase: params.useCase,
    platform: params.platform,
    architecture: params.architecture,
    formFactor: params.formFactor,
    footprint: params.footprint,
    statePreference: params.statePreference,
    cLibPreference: params.cLibPreference,
    initPreference: params.initPreference,
    experienceLevel: params.experienceLevel,
    maxRamMb: params.maxRamMb ? Number(params.maxRamMb) : undefined,
    prefersGui: flag(params.prefersGui),
    workflowStyle: params.workflowStyle,
    releaseCadence: params.releaseCadence,
    driverPhilosophy: params.driverPhilosophy,
    bootMedium: params.bootMedium,
    realtimeAudio: flag(params.realtimeAudio),
    requiresCustomBuild: flag(params.requiresCustomBuild),
    desktopEnv: params.desktopEnv,
    enableDistrobox: flag(params.enableDistrobox),
    enableNix: flag(params.enableNix),
    enableFlatpak: flag(params.enableFlatpak),
    dockerApp: params.dockerApp !== 'none' ? params.dockerApp : undefined,
    desktopApps: list(params.desktopApps),
    emulatorApps: list(params.emulatorApps)
  };

  if (params.peripherals) {
    raw.peripherals = list(params.peripherals);
  } else if (params.peripheralNeed) {
    raw.peripheralNeed = params.peripheralNeed;
    raw.peripherals = [params.peripheralNeed];
  }

  // Shared URLs are untrusted input: only allowlisted values may reach the matcher or recipe generators.
  return sanitizeCriteria(raw);
}

/**
 * Serializes strongly typed UserCriteria into standard URL query parameter key-values.
 */
export function serializeCriteriaToParams(
  criteria: UserCriteria,
  extra?: Record<string, string>
): Record<string, string> {
  const params: Record<string, string> = {
    v: String(CURRENT_SCHEMA_VERSION),
    ...(extra || {})
  };

  for (const [key, value] of Object.entries(criteria)) {
    if (value !== undefined && value !== null && value !== '') {
      if (Array.isArray(value)) {
        if (value.length > 0) {
          params[key] = value.join(',');
        }
      } else {
        params[key] = String(value);
      }
    }
  }

  return params;
}

/**
 * Converts UserCriteria directly into a shareable query string (e.g. "?v=1&tab=results&...").
 */
export function serializeCriteriaToQuery(
  criteria: UserCriteria,
  extra?: Record<string, string>
): string {
  const params = serializeCriteriaToParams(criteria, extra);
  const searchParams = new URLSearchParams(params);
  const qs = searchParams.toString();
  return qs ? `?${qs}` : '';
}
